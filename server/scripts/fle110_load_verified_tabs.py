"""FLE-110 — load the FLE-103 verified set into song_catalog.verified_tab.

    server/.venv/bin/python server/scripts/fle110_load_verified_tabs.py [options]

      --set PATH        verified set to load (default: the committed pilot set)
      --database-url U  override DATABASE_URL
      --dry-run         report what would change, write nothing
      --no-prune        leave verified_tab set on rows absent from the file

Scope item 2 of the issue: "a loader that reads pilot_verified_set.json into it
(and stays re-runnable — the file is regenerated by fle103_build_pilot_set.py)".

NO LLM, NO SPEND. Reads one JSON file and writes at most 64 rows.

Re-runnable, and what that actually requires
--------------------------------------------
Idempotence is the easy half: every write is an UPDATE keyed on
(lower(title), lower(artist)), so running twice over an unchanged file writes
nothing the second time and says so.

The half that matters is PRUNING. The file is the definition of the verified set,
not an append-only feed. If fle103_build_pilot_set.py drops a song — because Fret
withdraws a reading, or F2 stops holding for it — a loader that only UPDATEs
leaves that song's stale tab in the column, where the pilot filter keeps serving
it as hand-verified. Silent, and in the one direction that matters: a song nobody
stands behind any more, presented as checked. So rows not in the file have
verified_tab set back to NULL by default, and every pruned row is named in the
output. --no-prune exists for loading a partial file on purpose; it prints a
warning, because it is the unsafe mode.

Validation before writing
-------------------------
Every entry is shaped through app.models.song.Breakdown — the same model the
endpoint parses on the way out. A set that cannot round-trip that model is not
ground truth, and failing the load is better than finding out on a pilot user's
screen. Nothing is written unless ALL ten pass and ALL ten match a catalog row;
this is a verified SET, and loading eight of it is not a smaller success.

The check the issue asks for (`fle103_verify_pilot_tabs.py` passes against
whatever you load) is a separate command and stays separate — that script is
deliberately ignorant of this one, reads the file rather than the database, and
re-derives every pitch from the tuning array. Run it before this. The two are
chained in the FLE-110 writeup and in tests/test_fle110_verified_tab_serving.py,
which reads the rows back OUT of the database and runs the same eight checks on
what the column actually holds.
"""
import argparse
import asyncio
import json
import os
import pathlib
import sys
from decimal import Decimal

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from sqlalchemy import text  # noqa: E402  (needs the path fix)
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine  # noqa: E402

from app.verified_tabs import (  # noqa: E402
    PILOT_PLAYER_LEVEL_CAP,
    PILOT_SET_PATH,
    PROVENANCE_KEY,
    load_pilot_set,
    song_fingerprint,
    stored_value_for,
)

# The selector's catalog window, restated here so the coverage report is read off
# the same arithmetic the selector runs (today_song.py clause 5).
WINDOW = Decimal("0.15")
PLAYER_LEVEL_FLOOR = Decimal("0.20")


def _db_url(override: str | None) -> str:
    raw = override or os.environ.get(
        "DATABASE_URL", "postgresql://gt:devpass@localhost:5433/guitar_trainer"
    )
    for prefix in ("postgresql+asyncpg://", "postgresql://", "postgres://"):
        if raw.startswith(prefix):
            return raw if prefix.endswith("asyncpg://") else raw.replace(
                prefix, "postgresql+asyncpg://", 1
            )
    return raw


def _coverage(difficulties: list[Decimal], cap: Decimal) -> list[str]:
    """FLE-103 §5's coverage arithmetic, over whatever actually loaded.

    Reported against the CAPPED level range, because that is the range a pilot
    user can occupy once verified_tabs.PILOT_PLAYER_LEVEL_CAP applies. Printing
    the uncapped 0.20-1.00 sweep would show the two THIN windows the cap exists
    to make unreachable and read as a failure of this load.
    """
    lines, level = [], PLAYER_LEVEL_FLOOR
    while level <= cap:
        inside = [d for d in difficulties if abs(d - level) <= WINDOW]
        if not inside:
            lines.append(f"  DEAD  player_level {level}: no song in the window")
        elif len(inside) == 1:
            lines.append(
                f"  THIN  player_level {level}: 1 song — a reroll cannot move"
            )
        level += Decimal("0.01")
    return lines


async def run(args: argparse.Namespace) -> int:
    set_path = pathlib.Path(args.set) if args.set else PILOT_SET_PATH
    data = load_pilot_set(set_path)
    entries = data["songs"]
    source = str(set_path.name)
    print(f"set        {set_path}")
    print(f"songs      {len(entries)}")

    # --- Shape every entry first. Nothing touches the DB until all of them pass.
    payloads: dict[tuple[str, str], dict] = {}
    for entry in entries:
        key = (entry["title"].strip().lower(), entry["artist"].strip().lower())
        if key in payloads:
            print(f"FAIL       duplicate entry for {entry['title']!r}")
            return 1
        payloads[key] = stored_value_for(entry, source, data.get("schema_version"))
    print(f"validated  {len(payloads)}/{len(entries)} parse as Breakdown")

    engine = create_async_engine(_db_url(args.database_url), pool_pre_ping=True)
    factory = async_sessionmaker(engine, expire_on_commit=False)
    try:
        async with factory() as db:
            column = await db.scalar(
                text(
                    "SELECT 1 FROM information_schema.columns "
                    "WHERE table_name = 'song_catalog' AND column_name = 'verified_tab'"
                )
            )
            if not column:
                print(
                    "FAIL       song_catalog.verified_tab does not exist.\n"
                    "           Run `alembic upgrade head` (migration 0016) first.\n"
                    "           If alembic_version already reads 0016 or later, this\n"
                    "           is the FLE-103 §1c schema drift — the migration is\n"
                    "           ADD COLUMN IF NOT EXISTS, so re-running it is safe."
                )
                return 1

            rows = (
                await db.execute(
                    text(
                        "SELECT id, title, artist, difficulty, verified_tab "
                        "FROM song_catalog"
                    )
                )
            ).mappings().all()
            catalog = {
                (r["title"].strip().lower(), r["artist"].strip().lower()): r
                for r in rows
            }

            missing = [k for k in payloads if k not in catalog]
            if missing:
                for title, artist in missing:
                    print(f"FAIL       no song_catalog row for {title!r} by {artist!r}")
                print(
                    "           Nothing written. The verified set names songs the\n"
                    "           catalog does not carry; add them to the catalog or\n"
                    "           fix the title/artist spelling in the set."
                )
                return 1

            written, unchanged, pruned = [], [], []
            for key, payload in payloads.items():
                row = catalog[key]
                existing = row["verified_tab"]
                existing_sha = (
                    (existing or {}).get(PROVENANCE_KEY, {}).get("sha256")
                    if isinstance(existing, dict) else None
                )
                if existing_sha == payload[PROVENANCE_KEY]["sha256"]:
                    unchanged.append(row["title"])
                    continue
                written.append(row["title"])
                if not args.dry_run:
                    await db.execute(
                        text(
                            "UPDATE song_catalog SET verified_tab = CAST(:v AS jsonb) "
                            "WHERE id = :id"
                        ),
                        {"v": json.dumps(payload), "id": row["id"]},
                    )

            if args.no_prune:
                print(
                    "WARNING    --no-prune: a row whose song left the set keeps its "
                    "stale verified tab and stays servable."
                )
            else:
                for key, row in catalog.items():
                    if key not in payloads and row["verified_tab"] is not None:
                        pruned.append(row["title"])
                        if not args.dry_run:
                            await db.execute(
                                text(
                                    "UPDATE song_catalog SET verified_tab = NULL "
                                    "WHERE id = :id"
                                ),
                                {"id": row["id"]},
                            )

            if not args.dry_run:
                await db.commit()

            verb = "would write" if args.dry_run else "wrote"
            print(f"{verb:10} {len(written)}" + (f"  {', '.join(written)}" if written else ""))
            print(f"unchanged  {len(unchanged)}" + (f"  {', '.join(unchanged)}" if unchanged else ""))
            print(f"pruned     {len(pruned)}" + (f"  {', '.join(pruned)}" if pruned else ""))

            # --- Report the state the selector will actually see.
            #
            # PROJECTED, not re-queried. Under --dry-run nothing was written, so a
            # "SELECT WHERE verified_tab IS NOT NULL" here reports the state BEFORE
            # the load — which on a fresh database is zero rows, making every window
            # DEAD and the exit code 1 on a load that is in fact perfectly healthy.
            # That turns the one mode whose whole job is answering "is this file safe
            # to load" into a guaranteed false alarm. So the set is projected from
            # what this run decided: the catalog rows the file names, plus (only
            # under --no-prune) rows keeping a verified tab the file no longer names.
            # With writes enabled the projection equals the post-commit query.
            live = sorted(
                (
                    {"title": row["title"], "difficulty": row["difficulty"]}
                    for key, row in catalog.items()
                    if key in payloads
                    or (args.no_prune and row["verified_tab"] is not None)
                ),
                key=lambda r: r["difficulty"],
            )
            print(f"\nverified in catalog: {len(live)}")
            for r in live:
                print(f"  {r['difficulty']}  {r['title']}")

            problems = _coverage([r["difficulty"] for r in live], PILOT_PLAYER_LEVEL_CAP)
            print(
                f"\ncoverage over player_level [{PLAYER_LEVEL_FLOOR}, "
                f"{PILOT_PLAYER_LEVEL_CAP}] (the capped pilot range):"
            )
            if problems:
                print("\n".join(problems))
                print(
                    "  ^ a pilot user in one of these windows gets one song and a\n"
                    "    reroll that cannot move it — the FLE-49 collapse. Widen the\n"
                    "    set or lower verified_tabs.PILOT_PLAYER_LEVEL_CAP."
                )
            else:
                print("  no dead or thin windows — every level has 2+ songs")
            return 1 if problems else 0
    finally:
        await engine.dispose()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--set", help="path to a verified set JSON file")
    parser.add_argument("--database-url", help="override DATABASE_URL")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--no-prune",
        action="store_true",
        help="do not clear verified_tab on rows absent from the set (unsafe)",
    )
    return asyncio.run(run(parser.parse_args()))


if __name__ == "__main__":
    raise SystemExit(main())
