"""song_catalog: add verified_tab — somewhere to put a hand-checked tab

Revision ID: 0016
Revises: 0015
Create Date: 2026-10-05

FLE-110 — scope item 1. The place a hand-verified tab lives, so that verifying one
is not undone by the next generation.

Why a column on song_catalog and not a join table
-------------------------------------------------
The issue leaves the shape open ("a `verified_tab` JSONB column on `song_catalog`,
or a `verified_tabs` join table. Your call"). A column, because the relation is
one-to-one and there is no second axis to key on: there is exactly one verified
tab per catalog song, it is not versioned in the database (the committed file is
the version history, under git), and it is not per-user. A join table would buy
multiple verified tabs per song — an alternate arrangement, a different passage —
which nothing asks for today and which the serve path would then have to choose
between. The column can become a table the day a second row per song is wanted;
the reverse is the migration nobody wants to write.

NULL means "not hand-verified". It is the state of 54 of the 64 rows after the
loader runs, and it is what the pilot filter in app/selectors/today_song.py tests.

Why no CHECK on the JSON shape
------------------------------
Postgres can assert `jsonb_typeof(verified_tab) = 'object'` and little more that
is worth having. The real contract is "parses as app.models.song.Breakdown", which
is 500 lines of Pydantic including capo transposition and legato-target checks, and
restating a weak approximation of it in SQL would read as a guarantee it is not.
The guarantee lives where it can be complete: scripts/fle110_load_verified_tabs.py
validates every entry through the same `Breakdown` model the endpoint parses, and
refuses to write anything that fails. The one-object-per-row shape is instead
covered by tests/test_fle110_verified_tab_serving.py reading every row back.

Why no new index
----------------
`song_catalog_title_artist_uidx` (UNIQUE on lower(title), lower(artist), from
migration 0003) already covers every lookup this column adds — the selector's
EXISTS clauses, the breakdown endpoint's short-circuit, and the loader's match.
The partial `WHERE verified_tab IS NOT NULL` scans ten rows out of sixty-four; an
index for that would be ceremony.

IF NOT EXISTS, deliberately
---------------------------
FLE-103 §1c found production stamped at `alembic_version = 0015` with 0015's
`rights_status` column ABSENT — a migration whose effects are missing under a
version that claims them. Whatever produced that state (a stamp, a failed
partial apply) can produce it again, and the recovery for it is re-running the
chain. `ADD COLUMN IF NOT EXISTS` makes this migration safe to re-run and safe to
land on a database somebody has already patched by hand, which is the posture that
drift calls for. It is not a licence to skip the real diagnosis — that is filed
separately as the schema-drift bug.
"""
